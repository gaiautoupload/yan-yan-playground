const window={YanClassicShared:{app,state,persist:()=>calls.push('save')},YanSpeech:{cancel:()=>calls.push('cancel')},YanHideSeek:{start:()=>calls.push('seek')},YanPretendPlay:{start:()=>calls.push('pretend')}};
